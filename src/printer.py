# src/printer.py

import os
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from src.constants import REPORTS_DIR

class PDFPrinter:
    """
    Handles the generation of professional PDF shopping lists using ReportLab.
    """

    def __init__(self):
        """
        Initializes the PDF Printer and ensures the reports directory exists.
        """
        if not os.path.exists(REPORTS_DIR):
            os.makedirs(REPORTS_DIR)

    def generate_pdf(self, found_items: list[dict]) -> str:
        """
        Generates a PDF document containing the requested items and their shelf numbers.
        
        Args:
            found_items (list[dict]): A list of dictionaries containing 'name' and 'shelf' keys.
            
        Returns:
            str: The filepath of the generated PDF, or an empty string if generation failed.
        """
        if not found_items:
            print("No items to print.")
            return ""

        # Generate a unique filename based on the current timestamp
        timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"ShoppingList_{timestamp_str}.pdf"
        filepath = os.path.join(REPORTS_DIR, filename)

        try:
            # Create a canvas object for PDF generation
            c = canvas.Canvas(filepath, pagesize=letter)
            width, height = letter

            # Title
            c.setFont("Helvetica-Bold", 24)
            c.drawCentredString(width / 2.0, height - 50, "SHELFY AI")
            
            c.setFont("Helvetica-Bold", 16)
            c.drawCentredString(width / 2.0, height - 75, "Smart Shopping Assistant")

            # Date and Time
            current_datetime = datetime.now()
            date_str = current_datetime.strftime("%B %d, %Y")
            time_str = current_datetime.strftime("%I:%M %p")
            
            c.setFont("Helvetica", 12)
            c.drawString(50, height - 120, f"Date: {date_str}")
            c.drawString(50, height - 140, f"Time: {time_str}")
            c.drawString(50, height - 160, f"Total Items: {len(found_items)}")

            # Line separator
            c.line(50, height - 180, width - 50, height - 180)

            # Table Headers
            c.setFont("Helvetica-Bold", 14)
            c.drawString(50, height - 210, "Product Name")
            c.drawString(300, height - 210, "Shelf Location")
            
            c.line(50, height - 220, width - 50, height - 220)

            # Items List
            y_position = height - 250
            c.setFont("Helvetica", 12)
            
            for item in found_items:
                # Prevent writing off the bottom of the page
                if y_position < 100:
                    c.showPage()
                    y_position = height - 50
                    c.setFont("Helvetica", 12)
                
                c.drawString(50, y_position, f"- {item['name']}")
                c.drawString(300, y_position, item['shelf'])
                y_position -= 30
                
            # Footer
            c.line(50, 50, width - 50, 50)
            c.setFont("Helvetica-Oblique", 10)
            c.drawCentredString(width / 2.0, 30, "Generated by Shelfy AI")

            # Save the PDF
            c.save()
            print(f"Successfully generated PDF: {filepath}")
            return filepath
            
        except Exception as e:
            print(f"Failed to generate PDF: {e}")
            return ""

